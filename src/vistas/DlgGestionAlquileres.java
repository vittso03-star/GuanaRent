    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
     int fila = tblAlquileres.getSelectedRow();
    if (fila == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un alquiler de la tabla para eliminar");
        return;
    }

    int numAlquiler = (int) modelo.getValueAt(fila, 0);
    int confirmacion = JOptionPane.showConfirmDialog(this,
            "¿Está seguro de eliminar este alquiler?", "Confirmar",
            JOptionPane.YES_NO_OPTION);

    if (confirmacion == JOptionPane.YES_OPTION) {
        Alquiler aEliminar = buscar(numAlquiler);
        if (aEliminar != null) {
            listaAlquileres.remove(aEliminar);
            JOptionPane.showMessageDialog(this, "Alquiler eliminado correctamente");
            muestraTabla();
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

