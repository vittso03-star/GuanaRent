    private void txtBuscarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtBuscarKeyReleased
        String filtro = txtBuscar.getText().trim().toLowerCase();
    modelo.setRowCount(0);
    for (Alquiler a : listaAlquileres) {
        String nombreInquilino = buscarNombreInquilino(a.getCedInquilino());
        if (String.valueOf(a.getNumAlquiler()).contains(filtro)
                || nombreInquilino.toLowerCase().contains(filtro)) {
            String direccionVivienda = buscarDireccionVivienda(a.getIdVivienda());
            modelo.addRow(new Object[]{
                a.getNumAlquiler(), a.getFechContrato(), a.getCantMeses(),
                nombreInquilino, direccionVivienda, a.getPrecioAlquiler(), a.getEstado()
            });
        }
    }
}

private Alquiler buscar(int numAlquiler) {
    for (Alquiler a : listaAlquileres) {
        if (a.getNumAlquiler() == numAlquiler) {
            return a;
        }
    }
    return null;
    }//GEN-LAST:event_txtBuscarKeyReleased

