   private void muestraTabla() {
    String[] titulos = {"N° Alquiler", "Fecha Contrato", "Meses", "Inquilino", 
                         "Vivienda", "Precio", "Estado"};
    modelo = new DefaultTableModel(null, titulos) {
        @Override
        public boolean isCellEditable(int row, int col) {
            return false;
        }
    };
    tblAlquileres.setModel(modelo);
    modelo.setRowCount(0);

    for (Alquiler a : listaAlquileres) {
        String nombreInquilino = buscarNombreInquilino(a.getCedInquilino());
        String direccionVivienda = buscarDireccionVivienda(a.getIdVivienda());

        modelo.addRow(new Object[]{
            a.getNumAlquiler(), a.getFechContrato(), a.getCantMeses(),
            nombreInquilino, direccionVivienda, a.getPrecioAlquiler(), a.getEstado()
        });
    }
}

private String buscarNombreInquilino(long cedula) {
    for (Inquilino i : listaInquilinos) {
        if (i.getCedInqui() == cedula) {
            return i.getNomInqui();
        }
    }
    return "Desconocido";
}

private String buscarDireccionVivienda(int idVivienda) {
    for (Vivienda v : listaViviendas) {
        if (v.getIdVivienda() == idVivienda) {
            return v.getDireccion(); // ajusta al nombre real del getter en Vivienda
        }
    }
    return "Desconocida";
}
